// Drives forward with positive
void drive(float feet, float power){
  resetMotorEncoder(leftMotor);
  resetMotorEncoder(rightMotor);
  float speed = power > 127 ? 127: power;
  int distance = oneFoot * feet;

  while(getMotorEncoder(rightMotor) < distance && getMotorEncoder(leftMotor) < distance){
      float slowDown = driveControl(distance, getMotorEncoder(rightMotor));
      speed = slowDown > speed ? speed : slowDown;
      if(getMotorEncoder(rightMotor) > distance){
          motor[rightMotor] = 0;
      }
      else{
          motor[leftMotor] = speed;
      }
         if(getMotorEncoder(leftMotor) > distance){
             motor[leftMotor] = 0;
         }
         else{
             motor[rightMotor] = speed;
         }
  }
  wait1Msec(500);
}

