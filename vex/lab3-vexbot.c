// returns true if it detects something on sonar that can be picked up right in front of it
bool isDetectingNearObject() {
	return SensorValue(sonarIN) < 17 && SensorValue(sonarIN) > -1;
}

// returns true if it detects something on sonar but cannot reach it
bool isDetectingFarObject() {
	return SensorValue(sonarIN) > 17  && SensorValue(sonarIN) < 150 || SensorValue(sonarIN) == -1;
}

