// Not sure why I made this, slows down a tiny bit towards the end of the distance
float driveControl(int distance, int encoder){
	return 0.8 * (distance - abs(encoder));
}

// Slow the turn as it approaches the desired distance/angle
float turnControl(int distance, int encoder){
	return 0.3 * (distance - encoder);
}

//Left turns are negative
void turn(float degrees, int power){
  resetMotorEncoder(leftMotor);
  resetMotorEncoder(rightMotor);

  float angle = 515 * (degrees / 90);
  float speed = (power > 127) ? 127 : power;
  bool done = false;

  while((getMotorEncoder(leftMotor) < angle || getMotorEncoder(rightMotor) < angle) && !done){
  	float slowDown = turnControl(angle, getMotorEncoder(rightMotor));
  	speed = slowDown > speed ? speed : slowDown;

  	if(abs(getMotorEncoder(leftMotor)) > angle){
  			motor[leftMotor] = 0;
  	}
  	else{
  		motor[leftMotor] = speed;
  	}
  	if(abs(getMotorEncoder(rightMotor)) > angle){
  		motor[rightMotor] = 0;
  	}
  	else{
  		motor[rightMotor] = -speed;
  	}
  	done = (motor[rightMotor] == 0 && motor[leftMotor] == 0);
  }
  wait1Msec(500);
}

