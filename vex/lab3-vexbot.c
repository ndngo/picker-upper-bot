task UARTRx() {
 	while(true){
		char rcvChar;
  	rcvChar = getChar(uartOne);
  	wait1Msec(30);

		switch(rcvChar){
			case 'w':
				// forward
				writeDebugStreamLine("Drive forward.");
//				driveForward(1, 50);
				drive(1, 50);
				break;

			case 'a':
			  // turn left
				writeDebugStreamLine("Turn left.");
				turn(90, -50);
				break;

			case 's':
				// backward
				writeDebugStreamLine("Drive backwards.");
//				driveBackwards();
				drive(-1, 50);
				break;

			case 'd':
				// turn right
				writeDebugStreamLine("Turn right.");
				turn(90, 50);
				break;

			case 'e':
				// Lowers arm
				writeDebugStreamLine("Lower arm.");
				lowerArm();
				break;

			case 'r':
				// Raises arm
				writeDebugStreamLine("Raise arm.");
				raiseArm();
				break;

			case 'f':
				//opens claw
				writeDebugStreamLine("Open hand.");
				openHand();
				break;

			case 'g':
				writeDebugStreamLine("Close hand.");
				closeHand();
				break;

			default:
		}
	}
}

